struct DisplayData {
  uint8_t Data[1024];
  gpio_num_t scl;
  gpio_num_t sda;
  int invert;

  DisplayData(gpio_num_t sclPin = OLED_I2C_SCL,
              gpio_num_t sdaPin = OLED_I2C_SDA, int invert = 1)
      : scl(sclPin), sda(sdaPin), invert(invert) {
    memcpy(Data, DefaultData, sizeof(DefaultData));
  }
};

class SSD1306 {
private:
  SSD1306(gpio_num_t sclPin, gpio_num_t sdaPin, int invert);
  ~SSD1306();

  gpio_num_t _scl = OLED_I2C_SCL;
  gpio_num_t _sda = OLED_I2C_SDA;

  i2c_master_bus_handle_t bus_handle;
  i2c_master_dev_handle_t dev_handle;

  uint16_t _width = 128;
  uint16_t _height = 64;
  uint16_t _flip = 0;
  uint16_t _pages = 8; // 64高度是8,32高度是4

public:
  int _invert = 0;

  static SSD1306 &GetInstance(gpio_num_t scl = OLED_I2C_SCL,
                              gpio_num_t sda = OLED_I2C_SDA, int invert = 0) {
    static SSD1306 instance(scl, sda, invert);
    return instance;
  }

  // 删除拷贝构造函数和赋值运算符
  SSD1306(const SSD1306 &) = delete;
  SSD1306 &operator=(const SSD1306 &) = delete;

  void reset(gpio_num_t reset_pin);
  void full();

  void clear();

  void init();

  void invert(bool invert);

  void draw_pixel(int16_t x, int16_t y, uint16_t color);

  void display_image(int page, int seg, uint8_t *images, int width);

  void display_text(int page, const char *text, int text_len);

  void probe();

  esp_err_t contrast(int contrast);

  void hardware_scroll(scroll_type_t scroll);

  void error(esp_err_t res);

  esp_err_t probe_SSD1306();
};
